create table public.users (
  id bigint generated by default as identity primary key,
  username text not null,
  password_hash text not null,
  role text not null check (role in ('admin', 'merchant')),
  business_id text unique references public.businesses(id) on update cascade on delete restrict,
  demo_business_id text references public.businesses(id) on update cascade on delete set null,
  failed_attempts integer not null default 0 check (failed_attempts >= 0),
  locked_until timestamptz,
  first_name text,
  last_name text,
  email text,
  must_change_password boolean not null default false,
  created_at timestamptz not null default now(),
