create table public.public_lookup_limits (
  identifier_hash text primary key,
  window_started_at timestamptz not null,
  attempt_count integer not null check (attempt_count >= 0),
  updated_at timestamptz not null default now()
);
create index public_lookup_limits_updated_at_idx on public.public_lookup_limits(updated_at);

create function public.consume_coupon_lookup(p_identifier_hash text, p_now timestamptz default now())
returns table (allowed boolean, retry_after_seconds integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_count integer;
  current_window timestamptz;
begin
  insert into public.public_lookup_limits as limits (identifier_hash, window_started_at, attempt_count, updated_at)
  values (p_identifier_hash, p_now, 1, p_now)
  on conflict (identifier_hash) do update
    set window_started_at = case
          when limits.window_started_at <= p_now - interval '15 minutes' then p_now
          else limits.window_started_at
        end,
        attempt_count = case
          when limits.window_started_at <= p_now - interval '15 minutes' then 1
          when limits.attempt_count >= 10 then limits.attempt_count
          else limits.attempt_count + 1
        end,
        updated_at = p_now
  returning limits.attempt_count, limits.window_started_at
  into current_count, current_window;

  return query select
    current_count <= 10,
    case when current_count <= 10 then 0 else greatest(1, ceil(extract(epoch from (current_window + interval '15 minutes' - p_now))::numeric)::integer) end;
end;
$$;
revoke all on function public.consume_coupon_lookup(text, timestamptz) from public, anon, authenticated;

