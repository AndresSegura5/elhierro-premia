create table public.coupons (
  code text primary key check (code ~ '^EH-(BES|BIM|MER)-[A-HJ-KM-NP-Z][1-9][A-HJ-KM-NP-Z][1-9]{3}[A-HJ-KM-NP-Z]$'),
  race_id text not null references public.races(id) on update cascade on delete restrict,
  business_id text not null references public.businesses(id) on update cascade on delete restrict,
  amount_cents integer not null check (amount_cents > 0),
  used_cents integer not null default 0 check (used_cents between 0 and amount_cents),
  created_at timestamptz not null default now()
